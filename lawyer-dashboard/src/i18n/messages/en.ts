/** "For evidence" reads "for evidence" mid-sentence; an abbreviation keeps its capitals. */
const midSentence = (text: string) =>
  /^[A-Z][a-z]/.test(text) ? text.charAt(0).toLowerCase() + text.slice(1) : text

